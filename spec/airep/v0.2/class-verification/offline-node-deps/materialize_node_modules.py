#!/usr/bin/env python3
"""Materialize verifier_node_r2/node_modules from the vendored tarball bundle.

Offline and stdlib-only by design: a materializer that needed a package manager or a
third-party library to run would reintroduce the dependency it exists to remove.

Fail-closed at every step:
  * each tarball's sha256 must match MANIFEST.json;
  * each tarball's sha512 must match the SRI recorded in the frozen package-lock.json;
  * the closure must be exactly the expected packages -- no more, no fewer;
  * extraction rejects absolute paths, parent-directory escapes, and any symlink or
    hardlink whose target leaves the package directory;
  * after extraction, every package.json name+version is re-verified against the manifest.

Exit 0 only if every check passes. Never falls back to a system-installed Ajv.
"""
import base64
import hashlib
import io
import json
import pathlib
import shutil
import sys
import tarfile

HERE = pathlib.Path(__file__).resolve().parent
CV = HERE.parent
TARGET = CV / "verifier_node_r2" / "node_modules"
MANIFEST = json.loads((HERE / "MANIFEST.json").read_text(encoding="utf-8"))
LOCK = json.loads((CV / "verifier_node_r2" / "package-lock.json").read_text(encoding="utf-8"))


def fail(msg):
    print("FAIL: " + msg, file=sys.stderr)
    raise SystemExit(1)


def safe_extract(tar, dest, pkg):
    """Extract `package/...` members into dest, refusing anything that escapes it."""
    dest_res = str(dest.resolve())
    for m in tar.getmembers():
        if not (m.name == "package" or m.name.startswith("package/")):
            fail("%s: member outside package/ root: %r" % (pkg, m.name))
        rel = m.name[len("package"):].lstrip("/")
        if not rel:
            continue
        p = pathlib.PurePosixPath(rel)
        if p.is_absolute() or any(part == ".." for part in p.parts):
            fail("%s: unsafe path %r" % (pkg, m.name))
        out = dest / rel
        if not str(out.resolve().parent).startswith(dest_res):
            fail("%s: path escapes destination: %r" % (pkg, m.name))
        if m.issym() or m.islnk():
            tgt = pathlib.PurePosixPath(m.linkname)
            if tgt.is_absolute() or any(part == ".." for part in tgt.parts):
                fail("%s: link %r targets outside the package: %r" % (pkg, m.name, m.linkname))
            fail("%s: links are not expected in this closure (%r)" % (pkg, m.name))
        if m.isdir():
            out.mkdir(parents=True, exist_ok=True)
        elif m.isfile():
            out.parent.mkdir(parents=True, exist_ok=True)
            src = tar.extractfile(m)
            if src is None:
                fail("%s: unreadable member %r" % (pkg, m.name))
            out.write_bytes(src.read())
            out.chmod(0o644)
        else:
            fail("%s: unsupported member type in %r" % (pkg, m.name))


def main():
    lock_entries = {k.replace("node_modules/", ""): v
                    for k, v in LOCK["packages"].items() if k}
    expected = {n: r["version"] for n, r in MANIFEST["packages"].items()}
    if set(lock_entries) != set(expected):
        fail("lock closure != bundle closure: %s" % (set(lock_entries) ^ set(expected)))

    if TARGET.exists():
        shutil.rmtree(TARGET)
    TARGET.mkdir(parents=True)

    for name in sorted(MANIFEST["packages"]):
        rec = MANIFEST["packages"][name]
        blob = (HERE / "tarballs" / rec["tarball"]).read_bytes()

        got256 = hashlib.sha256(blob).hexdigest()
        if got256 != rec["sha256"]:
            fail("%s: sha256 mismatch\n  manifest %s\n  actual   %s"
                 % (name, rec["sha256"], got256))

        alg, b64 = lock_entries[name]["integrity"].split("-", 1)
        if alg != "sha512":
            fail("%s: unexpected SRI algorithm %s" % (name, alg))
        got512 = base64.b64encode(hashlib.sha512(blob).digest()).decode()
        if got512 != b64:
            fail("%s: lock SRI mismatch" % name)

        dest = TARGET / name
        dest.mkdir(parents=True)
        with tarfile.open(fileobj=io.BytesIO(blob), mode="r:gz") as tf:
            safe_extract(tf, dest, name)

        pj = json.loads((dest / "package.json").read_text(encoding="utf-8"))
        if pj.get("name") != name or pj.get("version") != rec["version"]:
            fail("%s: extracted identity %s@%s != expected %s@%s"
                 % (name, pj.get("name"), pj.get("version"), name, rec["version"]))
        print("  %-22s %-8s sha256-ok sri-ok identity-ok" % (name, rec["version"]))

    installed = sorted(p.name for p in TARGET.iterdir() if p.is_dir())
    if installed != sorted(expected):
        fail("materialized set %s != expected %s" % (installed, sorted(expected)))
    print("\nnode_modules materialized offline from %d vendored tarballs: %s"
          % (len(expected), TARGET))
    return 0


if __name__ == "__main__":
    sys.exit(main())
